-- Do not substitute Persian names into English or Russian public profile fields.
-- Missing translations remain NULL and are omitted by the localized profile renderer.
create or replace view public.rls_public_members with (security_invoker = true)
as
select
  user_id,
  coalesce(display_name, full_name) as display_name,
  category,
  country,
  city,
  institution,
  degree,
  specialty,
  bio,
  avatar_path,
  website_url,
  orcid,
  created_at,
  profile_headline,
  memberships,
  activities,
  publications,
  research_interests,
  languages,
  case when phone_public then phone else null::text end as phone,
  display_name_en,
  display_name_ru,
  full_name_en,
  full_name_ru,
  profile_headline_en,
  profile_headline_ru,
  country_en,
  country_ru,
  city_en,
  city_ru,
  institution_en,
  institution_ru,
  degree_en,
  degree_ru,
  specialty_en,
  specialty_ru,
  bio_en,
  bio_ru,
  memberships_en,
  memberships_ru,
  activities_en,
  activities_ru,
  publications_en,
  publications_ru,
  research_interests_en,
  research_interests_ru,
  languages_en,
  languages_ru,
  case when email_public then email else null::text end as email,
  researchgate_url,
  google_scholar_url,
  instagram_url,
  telegram_url,
  linkedin_url,
  x_url,
  articles_count,
  books_count,
  salutation,
  reviewed_at,
  member_number,
  membership_status,
  blog_url,
  full_name
from public.rls_profiles
where membership_status = 'approved' and is_public = true;

grant select on public.rls_public_members to anon, authenticated;
